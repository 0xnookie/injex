#!/usr/bin/env node
// Builds src/data/confusables.js from Unicode's confusables.txt (UTS #39): every single character that
// looks like one ASCII letter or digit, with that letter. Used for look-alike detection (whole-script
// spoofs: a word spelled entirely in Cyrillic look-alikes), for the skeleton the instruction check runs on, and by the cleaner.
//   node tools/build-confusables.mjs               → downloads the data for VERSION from unicode.org
//   node tools/build-confusables.mjs <file>        → reads a local confusables.txt
//
// Entries are stored as "<hex code point><target>" separated by spaces, so the data file itself has no
// look-alike letters in it (the repository scans itself for those).

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const VERSION = '17.0.0';
const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(ROOT, 'src', 'data', 'confusables.js');

async function source(file) {
  if (file) return readFileSync(file, 'utf8');
  for (const url of [`https://www.unicode.org/Public/security/${VERSION}/confusables.txt`, 'https://www.unicode.org/Public/security/latest/confusables.txt']) {
    const res = await fetch(url);
    if (res.ok) return res.text();
  }
  throw new Error('confusables.txt: download failed');
}

/** confusables.txt → [[code point, ASCII target]] for single characters that map to one ASCII letter / digit. */
export function parseConfusables(text) {
  const out = new Map();
  for (const line of text.split('\n')) {
    const m = /^([0-9A-F]{4,6})\s*;\s*([0-9A-F ]+?)\s*;/.exec(line.replace(/^\uFEFF/, ''));
    if (!m) continue;
    const src = parseInt(m[1], 16);
    const target = m[2].trim().split(/\s+/).map((h) => parseInt(h, 16));
    if (src < 0x80 || target.length !== 1) continue;
    let t = String.fromCharCode(target[0]);
    if (!/^[A-Za-z0-9]$/.test(t)) continue;
    // UTS #39 skeletons map capital-I look-alikes to "l"; keep the case a reader would see
    const ch = String.fromCodePoint(src);
    if (t === 'l' && /\p{Lu}/u.test(ch)) t = 'I';
    out.set(src, t);
  }
  return [...out].sort((a, b) => a[0] - b[0]);
}

async function main() {
  const text = await source(process.argv[2]);
  const pairs = parseConfusables(text);
  const header = (/^#\s*(confusables-[\d.]+\.txt)/m.exec(text) || [])[1] || 'confusables.txt';
  const body = pairs.map(([cp, t]) => cp.toString(16) + t).join(' ');
  const out = `// Generated by tools/build-confusables.mjs from Unicode ${header} (UTS #39) — do not edit by hand.
// Unicode data © Unicode, Inc., Unicode License v3. ${pairs.length} characters that look like one ASCII letter
// or digit, as "<hex code point><letter>" pairs. Read with src/core/confusables.js.

export const CONFUSABLES_VERSION = ${JSON.stringify(VERSION)};
export const CONFUSABLES_DATA = ${JSON.stringify(body)};
`;
  writeFileSync(OUT, out);
  console.log(`src/data/confusables.js: ${pairs.length} characters, ${(out.length / 1024).toFixed(1)} KB`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
