#!/usr/bin/env node
// Regenerates src/transforms/index.js: one static import per transform module in src/transforms/<category>/,
// keyed by file name (dashes → underscores), with the folder as category.
//
//   node tools/sync-transforms.mjs            write the index
//   node tools/sync-transforms.mjs --check    exit 1 if the committed index is out of date (CI)
//
// The output is committed, so the extension itself has no build step.

import { readdirSync, statSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'transforms');
const imports = [];
const entries = [];
let n = 0;
for (const cat of readdirSync(dir).sort()) {
  if (!statSync(join(dir, cat)).isDirectory()) continue;
  for (const file of readdirSync(join(dir, cat)).sort()) {
    if (!file.endsWith('.js')) continue;
    const key = file.replace(/\.js$/, '').replace(/-/g, '_');
    const id = `t${n++}`;
    imports.push(`import ${id} from './${cat}/${file}';`);
    entries.push(`  [${JSON.stringify(key)}, ${JSON.stringify(cat)}, ${id}],`);
  }
}

const out = `// Generated by tools/sync-transforms.mjs — do not edit by hand.
// ${n} transform modules.
${imports.join('\n')}

/** [key, category, transformer] */
export const TRANSFORM_ENTRIES = [
${entries.join('\n')}
];
`;
const target = join(dir, 'index.js');
if (process.argv.includes('--check')) {
  const cur = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== out) {
    console.error('src/transforms/index.js is out of date — run node tools/sync-transforms.mjs');
    process.exit(1);
  }
  console.log(`src/transforms/index.js is up to date (${n} transforms)`);
} else {
  writeFileSync(target, out);
  console.log(`src/transforms/index.js: ${n} transforms`);
}
