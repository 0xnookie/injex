#!/usr/bin/env node
// Builds src/data/emoji-data.js from Unicode's emoji-test.txt plus the keyword map in tools/emoji-words.json.
// Only fully-qualified emoji without skin-tone / hair modifiers are kept (the picker, Emoji Speak and the
// Tokenade carrier list don't need the ~2,000 variants).
//
//   node tools/build-emoji-data.mjs [--version 16.0]
//
// The output is committed, so the extension itself has no build step.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const vi = process.argv.indexOf('--version');
const version = vi > 0 ? process.argv[vi + 1] : '16.0';
const url = `https://unicode.org/Public/emoji/${version}/emoji-test.txt`;

const res = await fetch(url);
if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
const text = await res.text();
const words = JSON.parse(readFileSync(join(root, 'tools/emoji-words.json'), 'utf8'));

const STOP = new Set(['with', 'and', 'the', 'for', 'of', 'in', 'on']);
const EXTRA = {
  grinning: ['smile', 'happy', 'grin'],
  'tears of joy': ['laugh', 'lol', 'funny'],
  heart: ['love', 'like'],
  'thumbs up': ['good', 'yes', 'approve', 'like'],
  'thumbs down': ['bad', 'no', 'disapprove'],
  waving: ['hello', 'hi', 'bye', 'wave'],
  clapping: ['applause', 'clap', 'praise'],
  folded: ['pray', 'thanks', 'please'],
  fire: ['hot', 'lit', 'flame'],
  crying: ['sad', 'tear', 'cry'],
  skull: ['dead', 'death'],
  hundred: ['100', 'perfect'],
  collision: ['boom', 'bang', 'explosion'],
  dog: ['puppy', 'pet'],
  cat: ['kitty', 'pet'],
  sun: ['sunny', 'day'],
  moon: ['night'],
  star: ['favorite'],
  rainbow: ['pride', 'colorful'],
};
const MODIFIER = /skin tone|: (?:red|curly|white) hair|bald/i;

const groups = [];
const rows = [];
let group = '';
for (const line of text.split('\n')) {
  const g = line.match(/^# group: (.+)$/);
  if (g) {
    group = g[1].trim();
    if (group !== 'Component') groups.push(group);
    continue;
  }
  const m = line.match(/^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*\S+\s+E\d+\.\d+\s+(.+)$/);
  if (!m || group === 'Component') continue;
  const name = m[2].trim();
  if (MODIFIER.test(name)) continue;
  const emoji = String.fromCodePoint(...m[1].trim().split(/\s+/).map((h) => parseInt(h, 16)));
  const kw = new Set(
    name
      .toLowerCase()
      .replace(/[():“”"!.,]/g, '')
      .split(/[\s-]+/)
      .filter((w) => w.length > 2 && !STOP.has(w)),
  );
  for (const [trigger, extras] of Object.entries(EXTRA)) if (name.toLowerCase().includes(trigger)) extras.forEach((k) => kw.add(k));
  for (const k of words[emoji] || []) kw.add(k);
  rows.push([emoji, name, groups.indexOf(group), [...kw].join(' ')]);
}

const out = `// Emoji data: ${rows.length} fully-qualified emoji from Unicode emoji-test.txt ${version}
// (https://unicode.org/Public/emoji/${version}/), keywords merged with tools/emoji-words.json.
// Generated by tools/build-emoji-data.mjs — do not edit by hand.
// Row: [emoji, official name, group index, space-separated keywords]

export const EMOJI_GROUPS = ${JSON.stringify(groups)};

export const EMOJI_ROWS = [
${rows.map((r) => '  ' + JSON.stringify(r)).join(',\n')}
];
`;
writeFileSync(join(root, 'src/data/emoji-data.js'), out);
console.log(`src/data/emoji-data.js: ${rows.length} emoji in ${groups.length} groups (${(out.length / 1024).toFixed(0)} KB)`);
