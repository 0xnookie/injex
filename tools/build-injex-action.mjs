// Builds the thin `injex-action` repository (for a GitHub Marketplace listing that holds nothing but the
// action) from action.yml: the same name, inputs and outputs, and one step that runs this repository's
// action at a release tag. node tools/build-injex-action.mjs [--ref v1.4.0] [--out dist/injex-action]

import { mkdirSync, readFileSync, writeFileSync, cpSync } from 'node:fs';
import { join, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

/** Names of the keys directly under a top-level block ("inputs:" / "outputs:") of an action.yml. */
export function blockKeys(yml, block) {
  const m = new RegExp(`^${block}:\\n((?:(?: {2}.*)?\\n)*)`, 'm').exec(yml);
  return m ? Array.from(m[1].matchAll(/^ {2}([a-z][a-z0-9-]*):\s*$/gm), (x) => x[1]) : [];
}

/** The thin action.yml: everything above "runs:" kept, outputs read from the one forwarding step. */
export function thinAction(yml, ref) {
  const head = yml.slice(0, yml.search(/^runs:/m)).replace(/\$\{\{ steps\.[a-z-]+\.outputs\.([a-z-]+) \}\}/g, '$${{ steps.injex.outputs.$1 }}');
  const inputs = blockKeys(yml, 'inputs');
  return (
    `# Generated by tools/build-injex-action.mjs from github.com/0xnookie/injex/action.yml — edit that file.\n` +
    head +
    `runs:\n  using: composite\n  steps:\n    - id: injex\n      uses: 0xnookie/injex@${ref}\n      with:\n` +
    inputs.map((k) => `        ${k}: \${{ inputs.${k} }}\n`).join('')
  );
}

export function readme(ref) {
  return `# injex-action

Fail the build on hidden prompt injection — invisible Unicode, look-alike letters, hidden comments and white
text in code, docs, PDFs and Word files — and on risky AI-agent configuration.

This repository only holds the GitHub Marketplace listing. The action runs
[0xnookie/injex](https://github.com/0xnookie/injex) at \`${ref}\`; inputs, outputs and documentation are
the same as there.

\`\`\`yaml
- uses: actions/checkout@v5
- uses: 0xnookie/injex-action@${ref}
  with:
    fail-on: high
    sarif: injex.sarif
\`\`\`

Licence: AGPL-3.0-or-later, like injex.
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1].replace(/\//g, sep)) {
  const arg = (k, d) => (process.argv.includes(k) ? process.argv[process.argv.indexOf(k) + 1] : d);
  const ref = arg('--ref', 'v' + JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version);
  const out = arg('--out', join(ROOT, 'dist', 'injex-action'));
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, 'action.yml'), thinAction(readFileSync(join(ROOT, 'action.yml'), 'utf8'), ref));
  writeFileSync(join(out, 'README.md'), readme(ref));
  cpSync(join(ROOT, 'LICENSE'), join(out, 'LICENSE'));
  console.log(`${out}: action.yml → 0xnookie/injex@${ref}`);
}
